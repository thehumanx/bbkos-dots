@unittest.skipUnless(shutil.which("lua5.4"), "lua5.4 not installed")
class HyprLuaTest(unittest.TestCase):
    def run_lua(self, text):
        with tempfile.TemporaryDirectory() as d:
            f = Path(d, "hypr-theme.lua")
            f.write_text(text)
            r = subprocess.run(["lua5.4", "-e", LUA_DUMP.replace("arg[1]", repr(str(f))), ],
                               capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stderr)
        return dict(l.split("=", 1) for l in r.stdout.splitlines())

    def test_touchpad_settings_render_into_the_one_config_call(self):
        s = make_settings("dark")
        s["touchpad"].update(naturalScroll=True, scrollMethod="2fg", tapButtonMap="lmr", dragLock=1,
                             swipe4Up="close", swipe3Down="workspace", swipe4Left="float")
        t = render.tokens(make_palette("dark"), s)
        text = render.render_hypr_lua(t, s)
        self.assertEqual(text.count("hl.config("), 1)
        for line in ('scroll_method = "2fg",', "natural_scroll = true,", 'tap_button_map = "lmr",', "drag_lock = 1,",
                     'hl.gesture({ fingers = 4, direction = "up", action = "close" })',
                     'hl.gesture({ fingers = 3, direction = "down", action = "workspace" })',
                     'hl.gesture({ fingers = 4, direction = "left", action = "float" })'):
            self.assertIn(line, text)
        self.assertNotIn("fingers = 4, direction = \"down\"", text)  # swipe4Down is "none"
        self.assertEqual(self.run_lua_text(text), 0)

    def test_grid_mode_renders_flat_windows_and_a_light_inactive_border(self):
        s = make_settings("dark")
        s["shell"]["gridMode"] = True
        g = settings.effective(s)
        t = render.tokens(make_palette("dark"), g)
        text = render.render_hypr_lua(t, g)
        for line in ("gaps_in = 0,", "gaps_out = 0,", "border_size = 1,", "rounding = 0,", "shadow = { enabled = false,"):
            self.assertIn(line, text)
        self.assertIn(f'inactive_border = "rgba({t["fg"].lstrip("#")}40)"', text)
        self.assertEqual(self.run_lua_text(text), 0)
        off = render.render_hypr_lua(t, make_settings("dark"))      # grid off: the owner's values, the palette border
        self.assertIn("gaps_out = 20,", off)
        self.assertNotIn("40)\"", off.split("inactive_border")[1].split("\n")[0])

    def test_overview_swipes_render_as_lua_functions(self):
        s = make_settings("dark")
        s["touchpad"].update(swipe3Up="overview", swipe3Down="overview-close")
        t = render.tokens(make_palette("dark"), s)
        text = render.render_hypr_lua(t, s)
        self.assertIn(
            'hl.gesture({ fingers = 3, direction = "up", '
            'action = function() hl.exec_cmd("qs ipc call overview open") end })', text)
        self.assertIn(
            'hl.gesture({ fingers = 3, direction = "down", '
            'action = function() hl.exec_cmd("qs ipc call overview close") end })', text)
        self.assertEqual(self.run_lua_text(text), 0)

    def test_touchpad_defaults_leave_hyprland_defaults_in_place(self):
        s = make_settings("dark")
        t = render.tokens(make_palette("dark"), s)
        text = render.render_hypr_lua(t, s)
        self.assertNotIn("scroll_method", text)
        self.assertNotIn("tap_button_map", text)
        self.assertNotIn("hl.gesture", text)

    def run_lua_text(self, text):
        with tempfile.TemporaryDirectory() as d:
            f = Path(d, "hypr-theme.lua")
            f.write_text(text)
            r = subprocess.run(["lua5.4", "-e", f"assert(loadfile({repr(str(f))}))"], capture_output=True, text=True)
        return r.returncode

    def test_hypr_lua_is_valid_lua_and_sets_every_windows_knob(self):
        for mode, tweak in (("dark", {}), ("light", {"gapsIn": 7, "activeOpacity": 0.85,
                                                      "shadowEnabled": False, "blurEnabled": False,
                                                      "animations": False, "blurPasses": 4})):
            with self.subTest(mode=mode):
                s = make_settings(mode)
                s["windows"].update(tweak)
                t = render.tokens(make_palette(mode), s)
                got = self.run_lua(render.render_hypr_lua(t, s))
                w = s["windows"]
                lua_b = lambda b: "true" if b else "false"
                self.assertEqual(got["1"], str(w["gapsIn"]))
                self.assertEqual(got["2"], str(w["gapsOut"]))
                self.assertEqual(got["3"], str(w["borderSize"]))
                self.assertEqual(got["4"], "rgba(%see)" % t["borderActive1"][1:])
                self.assertEqual(got["5"], "rgba(%see)" % t["borderActive2"][1:])
                self.assertEqual(got["6"], "45")
                self.assertEqual(got["7"], "rgba(%saa)" % t["borderInactive"][1:])
                self.assertEqual(got["8"], str(w["rounding"]))
                self.assertAlmostEqual(float(got["9"]), w["activeOpacity"])
                self.assertAlmostEqual(float(got["10"]), w["inactiveOpacity"])
                self.assertEqual(got["11"], lua_b(w["shadowEnabled"]))
                self.assertEqual(got["12"], str(w["shadowRange"]))
                self.assertEqual(got["13"], lua_b(w["blurEnabled"]))
                self.assertEqual(got["14"], str(w["blurSize"]))
                self.assertEqual(got["15"], str(w["blurPasses"]))
                self.assertEqual(got["16"], lua_b(w["animations"]))
                self.assertEqual(got["17"], "ff" + t["bg"][1:])

    def test_motion_uses_the_shared_curves_and_reduce_motion_drops_movement(self):
        for reduce, on, style in ((False, "true", "slide"), (True, "false", "fade")):
            with self.subTest(reduce=reduce):
                s = make_settings()
                s["shell"]["reduceMotion"] = reduce
                got = self.run_lua(render.render_hypr_lua(tok(), s))
                self.assertEqual((got["20"], got["21"]), ("0.23", "0.32"))   # Emil Kowalski's ease-out, as in Theme.qml
                self.assertEqual(got["22"], on)
                self.assertEqual(got["23"], style)
                self.assertEqual(got["24"], "bbkDrawer")
                self.assertEqual(got["25"], "2.2")

    def bar_rule(self, opacity, blur):
        s = make_settings()
        s["shell"].update(barOpacity=opacity, barBlur=blur)
        got = self.run_lua(render.render_hypr_lua(tok(), s))
        return got["18"], got["19"]

    def test_hypr_lua_never_emits_a_bar_layer_rule(self):
        # The bar draws its own tunable blur (shell.barBlurAmount); Hyprland's layer blur uses the windows' blur settings.
        for opacity, blur in ((1.0, False), (0.6, True), (1.0, True), (0.6, False)):
            self.assertEqual(self.bar_rule(opacity, blur), ("none", "none"))

    def test_hypr_lua_is_pure_data(self):
        text = render.render_hypr_lua(tok(), make_settings())
        for bad in ("function", "os.", "io.", "require", "#!"):
            self.assertNotIn(bad, text)


