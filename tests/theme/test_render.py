class TokensTest(unittest.TestCase):
    def test_tints_turn_the_wallpaper_hue_and_keep_the_floor(self):
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                t = tok(mode)
                hues = {k: contrast.to_oklch(t[k])[2] for k in ("accent", "secondary", "tertiary")}
                self.assertEqual(len({round(h) for h in hues.values()}), 3, hues)
                for k in ("secondary", "tertiary"):
                    self.assertGreaterEqual(contrast.ratio(t[k], t["bg"]), 3.0, k)
                for k in ("accentSoft", "secondarySoft", "tertiarySoft", "surfaceHigh"):
                    self.assertRegex(t[k], r"^#[0-9a-f]{6}$", k)

    def test_accent_strength_scales_the_chroma_and_keeps_hue_lightness_and_floors(self):
        keys = ("accent", "secondary", "tertiary", "accentSoft", "secondarySoft", "tertiarySoft")
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                full = tok(mode)
                s = make_settings(mode)
                s["colors"]["accentStrength"] = 1.0
                self.assertEqual(render.tokens(make_palette(mode), s), full)         # 100 %: nothing changes
                s["colors"]["accentStrength"] = 0.5
                half = render.tokens(make_palette(mode), s)
                for k in ("accentSoft", "secondarySoft", "tertiarySoft"):
                    (l0, c0, h0), (l1, c1, h1) = contrast.to_oklch(full[k]), contrast.to_oklch(half[k])
                    if k == "accentSoft":
                        self.assertAlmostEqual(c1, c0 * 0.5, delta=0.02, msg=k)
                    else:       # the turned hues were gamut-clipped at 100 %, so they keep a little more than half
                        self.assertLess(c1, c0, k)
                    self.assertAlmostEqual(l1, l0, delta=0.03, msg=k)
                    self.assertLess(abs((h1 - h0 + 180) % 360 - 180), 8, k)
                for k in ("secondary", "tertiary"):
                    self.assertGreaterEqual(contrast.ratio(half[k], half["bg"]), 3.0, k)
                s["colors"]["accentStrength"] = 0.0
                grey = render.tokens(make_palette(mode), s)
                for k in keys:
                    self.assertLess(contrast.to_oklch(grey[k])[1], 0.02, k)
                for k in ("secondary", "tertiary"):
                    self.assertGreaterEqual(contrast.ratio(grey[k], grey["bg"]), 3.0, k)
                self.assertEqual(grey["fg"], full["fg"])                              # text, surfaces and warn/crit are not touched
                self.assertEqual(grey["bg"], full["bg"])
                for k in ("warn", "crit"):      # not scaled; the floor lift may move them a hair when a surface they sit on changes
                    (l0, c0, _), (l1, c1, _) = contrast.to_oklch(full[k]), contrast.to_oklch(grey[k])
                    self.assertAlmostEqual(l1, l0, delta=0.02, msg=k)
                    self.assertAlmostEqual(c1, c0, delta=0.01, msg=k)

    def test_a_grey_wallpaper_keeps_every_tint_grey(self):
        p = dict(make_palette("dark"), tone_primary="#c0c0c0", soft_primary="#404040")
        t = render.tokens(p, make_settings())
        for k in ("secondary", "tertiary", "secondarySoft", "tertiarySoft"):
            self.assertLess(contrast.to_oklch(t[k])[1], 0.02, k)

    def test_tokens_apply_contrast_floors(self):
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                t = tok(mode)
                self.assertEqual(set(t), {"bg", "surface", "fg", "dim", "accent", "warn", "crit",
                                          "outline", "borderActive1", "borderActive2",
                                          "borderInactive", "secondary", "tertiary", "accentSoft",
                                          "secondarySoft", "tertiarySoft", "surfaceHigh", "ansi"})
                for k in ("fg", "dim", "accent", "warn", "crit", "secondary", "tertiary"):
                    self.assertGreaterEqual(contrast.ratio(t[k], t["bg"]), 4.5, k)
                self.assertEqual(len(t["ansi"]), 16)
                for i, c in enumerate(t["ansi"]):
                    self.assertRegex(c, HEX)
                    if i:
                        self.assertGreaterEqual(contrast.ratio(c, t["bg"]), 4.5, f"ansi {i}")

    def test_ansi_layout_and_bright_shift(self):
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                t = tok(mode)
                a = t["ansi"]
                bg = render.tokens(make_palette(mode), make_settings(mode))["bg"]
                variant = contrast.ensure_contrast(make_palette(mode)["on_surface_variant"], bg, 4.5)
                self.assertEqual((a[0], a[7], a[8], a[15]), (t["surface"], variant, t["dim"], t["fg"]))
                for i in range(1, 7):
                    la, lb = contrast.luminance(a[i]), contrast.luminance(a[i + 8])
                    if mode == "dark":
                        self.assertGreater(lb, la, i)
                    else:
                        self.assertLess(lb, la, i)

    def test_bright_ansi_keep_identity(self):
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                t = tok(mode)
                for i in range(1, 7):
                    n, b = t["ansi"][i], t["ansi"][i + 8]
                    self.assertGreaterEqual(contrast.ratio(b, n), 1.12, f"bright {i + 8} vs normal")
                    self.assertGreaterEqual(contrast.ratio(b, t["fg"]), 1.10, f"bright {i + 8} vs fg")
                    d = abs(contrast.to_oklch(b)[2] - contrast.to_oklch(n)[2])
                    self.assertLessEqual(min(d, 360 - d), 6, f"hue {i + 8}")
                    for c in (n, b):
                        self.assertGreaterEqual(contrast.ratio(c, t["bg"]), 4.5)

    def test_ansi_colours_stay_muted(self):
        roles = ("ansi_red", "ansi_green", "ansi_yellow", "ansi_blue", "ansi_magenta", "ansi_cyan")
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                p = make_palette(mode)
                t = render.tokens(p, make_settings(mode))
                for i, role in enumerate(roles, 1):
                    src = contrast.to_oklch(p[role])[1]
                    for idx in (i, i + 8):
                        # 0.01 allows for 8-bit rounding of the output hex
                        self.assertLessEqual(contrast.to_oklch(t["ansi"][idx])[1], src + 0.01,
                                             f"{role} ansi {idx}")

    def test_mapping(self):
        p = make_palette("dark")
        t = render.tokens(p, make_settings())
        self.assertEqual(t["bg"], p["surface"])
        self.assertEqual(t["surface"], p["surface_container"])
        self.assertEqual(t["borderActive1"], contrast.ensure_contrast(p["primary"], t["bg"], 3.0))
        self.assertEqual(t["borderActive2"], contrast.ensure_contrast(p["tertiary"], t["bg"], 3.0))
        self.assertEqual(t["borderInactive"], p["outline_variant"])
        self.assertEqual(t["outline"], p["outline"])
        # dim starts from `outline` and is only lifted along lightness, never re-hued
        self.assertLess(abs(contrast.to_oklch(t["dim"])[2] - contrast.to_oklch(p["outline"])[2]), 8)

    def test_dim_is_clearly_secondary_to_fg(self):
        # dim comes from Material `outline`: a visible secondary tier under fg. It must read at 4.5:1 on every surface text
        # sits on (the raised ones are lighter than bg in a dark theme), which pulls it closer to fg than a bg-only floor did.
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                t = tok(mode)
                self.assertGreaterEqual(contrast.ratio(t["fg"], t["dim"]), 1.5)
                self.assertGreaterEqual(contrast.ratio(t["dim"], t["bg"]), 4.5)

    def test_ansi7_and_ansi8_distinct(self):
        # 7 (white) from on_surface_variant, 8 (bright black) from dim: must not collapse into one grey.
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                a = tok(mode)["ansi"]
                self.assertGreaterEqual(contrast.ratio(a[7], a[8]), 1.25)

    def near_grey_palette(self, mode):
        # The owner's live fidelity palette (2026-10-18): matugen returned yellow and cyan as pure
        # white (chroma 0) and green as almost white; tokens() used to render 3 = 6 and 11 = 14.
        p = make_palette(mode)
        p.update(ansi_yellow="#ffffff", ansi_cyan="#ffffff", ansi_green="#e8ffea")
        return p

    def test_near_grey_roles_get_distinct_canonical_hues(self):
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                t = render.tokens(self.near_grey_palette(mode), make_settings(mode))
                for group in (range(1, 7), range(9, 15)):
                    lch = [contrast.to_oklch(t["ansi"][i]) for i in group]
                    for i, (_, c, _h) in enumerate(lch):
                        self.assertGreaterEqual(c, 0.05, f"ansi {group[i]} chroma")
                    for i in range(6):
                        for j in range(i + 1, 6):
                            d = abs(lch[i][2] - lch[j][2])
                            self.assertGreaterEqual(min(d, 360 - d), 20,
                                                    f"ansi {group[i]} vs {group[j]} hue gap")
                for i in range(1, 7):
                    for c in (t["ansi"][i], t["ansi"][i + 8]):
                        self.assertGreaterEqual(contrast.ratio(c, t["bg"]), 3.0, f"ansi {i}")

    def test_near_grey_repair_uses_role_hue_and_bounded_chroma(self):
        canon = {"ansi_green": 142, "ansi_yellow": 100, "ansi_cyan": 195}
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                t = render.tokens(self.near_grey_palette(mode), make_settings(mode))
                for i, role in enumerate(render.ANSI_ROLES, 1):
                    if role not in canon:
                        continue
                    for idx in (i, i + 8):
                        _, c, h = contrast.to_oklch(t["ansi"][idx])
                        d = abs(h - canon[role])
                        self.assertLessEqual(min(d, 360 - d), 6, f"{role} ansi {idx} hue")
                        self.assertLessEqual(c, render.NEAR_GREY_MIN_CHROMA + 0.01, f"{role} ansi {idx}")

    def test_near_grey_repair_leaves_saturated_roles_alone(self):
        for mode in ("dark", "light"):
            with self.subTest(mode=mode):
                before = render.tokens(make_palette(mode), make_settings(mode))["ansi"]
                after = render.tokens(self.near_grey_palette(mode), make_settings(mode))["ansi"]
                for i in (1, 4, 5):  # red, blue, magenta untouched
                    self.assertEqual(before[i], after[i])
                    self.assertEqual(before[i + 8], after[i + 8])

    def test_low_contrast_inputs_are_corrected(self):
        p = make_palette("dark")
        p.update(on_surface=p["surface"], on_surface_variant=p["surface"], primary=p["surface"],
                 warn=p["surface"], error=p["surface"], ansi_red=p["surface"])
        t = render.tokens(p, make_settings())
        self.assertGreaterEqual(contrast.ratio(t["fg"], t["bg"]), 4.5)
        self.assertGreaterEqual(contrast.ratio(t["ansi"][1], t["bg"]), 4.5)
        self.assertGreaterEqual(contrast.ratio(t["ansi"][9], t["bg"]), 4.5)


