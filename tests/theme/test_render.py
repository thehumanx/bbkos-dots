    def test_lock_text_is_inert(self):
        for raw in ("Hi $HOME", "$(reboot)", "`reboot`", "cmd[update:1] rm -rf ~", "trailing\\", "a\nb", "x" * 2000, ""):
            out = render.lock_text(raw)
            self.assertNotIn("cmd[", out, raw)
            self.assertNotIn("`", out, raw)
