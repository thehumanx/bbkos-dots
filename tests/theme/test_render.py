class GtkReloadTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.css("#ff6600", "on")
        self.home = self.tmp / "home"
        (self.home / ".local/share/themes").mkdir(parents=True)
        self.icons = self.tmp / "icons"
        (self.icons / "scalable/places").mkdir(parents=True)
        (self.icons / "scalable/places/folder.svg").write_text('<svg fill="#62a0ea"/>')
        self.gs = {"gtk-theme": "Adwaita", "color-scheme": "default", "icon-theme": "Adwaita"}
        self.calls = []

    def css(self, accent, folders):
        (self.tmp / "gtk.css").write_text(f"/* mode: light */\n/* accent: {accent} */\n/* folders: {folders} */\n")

    def run_reload(self, parent=True):
        from bbkos_theme import reload as R
        if parent:
            p = self.home / ".local/share/themes/adw-gtk3/gtk-3.0"
            p.mkdir(parents=True, exist_ok=True)
            (p / "gtk.css").write_text("/* adw */")
        orig = R.subprocess.run

        def run(argv, **kw):
            self.calls.append(argv[1:])
            if argv[1] == "set":
                self.gs[argv[3]] = argv[4]
            return SimpleNamespace(returncode=0, stdout=f"'{self.gs.get(argv[-1], '')}'\n", stderr="")
        R.subprocess.run = run
        self.addCleanup(setattr, R.subprocess, "run", orig)
        return R.reload_gtk(self.tmp, {"HOME": str(self.home), "PATH": "/usr/bin"},
                            which=lambda *a, **k: "/usr/bin/gsettings",
                            system_themes=self.tmp / "system-themes", system_icons=self.icons, real_home=self.home)

    def sets(self, key):
        return [c[3] for c in self.calls if c[0] == "set" and c[2] == key]

    def test_writes_a_theme_on_the_light_parent_and_switches_to_it(self):
        self.assertEqual(self.run_reload(), [])
        self.assertEqual(self.sets("gtk-theme"), ["bbkos-a"])
        self.assertEqual(self.sets("color-scheme"), ["prefer-light"])
        theme = (self.home / ".local/share/themes/bbkos-a/gtk-3.0/gtk.css").read_text()
        self.assertIn("adw-gtk3/gtk-3.0/gtk.css", theme)
        self.assertIn(str(self.tmp / "gtk.css"), theme)

    def test_same_colours_switch_nothing_new_colours_flip_the_name(self):
        self.run_reload()
        self.calls.clear()
        self.run_reload()
        self.assertEqual(self.sets("gtk-theme"), [])                      # nothing changed: open apps are left alone
        self.css("#00ff00", "on")
        self.run_reload()
        self.assertEqual(self.sets("gtk-theme"), ["bbkos-b"])             # GTK reloads only on a new name
        self.css("#0000ff", "on")
        self.run_reload()
        self.assertEqual(self.sets("gtk-theme"), ["bbkos-b", "bbkos-a"])

    def test_folder_icons_follow_the_accent_and_switch_off(self):
        self.run_reload()
        icon = (self.home / ".local/share/icons/bbkos-icons-a/scalable/places/folder.svg").read_text()
        self.assertNotIn("#62a0ea", icon)
        self.assertEqual(self.sets("icon-theme"), ["bbkos-icons-a"])
        self.run_reload()
        self.assertEqual(self.sets("icon-theme"), ["bbkos-icons-a"])     # same accent: no switch
        self.css("#00ff00", "on")
        self.run_reload()
        self.assertEqual(self.sets("icon-theme"), ["bbkos-icons-a", "bbkos-icons-b"])
        self.css("#ff6600", "off")
        self.run_reload()
        self.assertEqual(self.gs["icon-theme"], "Adwaita")

    def test_does_nothing_without_adw_gtk3(self):
        self.assertEqual(self.run_reload(parent=False), [])
        self.assertEqual(self.calls, [])

    def test_never_touches_gsettings_from_a_temp_home(self):
        from bbkos_theme import reload as R
        orig = R.subprocess.run
        R.subprocess.run = lambda argv, **kw: self.calls.append(argv) or SimpleNamespace(stdout="''", returncode=0)
        self.addCleanup(setattr, R.subprocess, "run", orig)
        self.assertEqual(R.reload_gtk(self.tmp, {"HOME": str(self.home), "PATH": "/usr/bin"},
                                      which=lambda *a, **k: "/usr/bin/gsettings", real_home=self.tmp / "elsewhere"), [])
        self.assertEqual(self.calls, [])
