def make_palette(mode):
    def run(argv):
        return SimpleNamespace(returncode=0, stdout=(FIX / "matugen-sample.json").read_text(), stderr="")
    return palette.generate(None, mode=mode, scheme="tonal-spot", source_index=0, contrast=0.0,
                            runner=run, config=Path("/nonexistent.toml"))


def make_settings(mode="dark"):
    s = copy.deepcopy(settings.DEFAULTS)
    s["colors"]["mode"] = mode
    return s


def tok(mode="dark"):
    return render.tokens(make_palette(mode), make_settings(mode))


