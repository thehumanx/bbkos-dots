class HyprlockRenderTest(unittest.TestCase):
    @staticmethod
    def _settings(**lock):
        s = copy.deepcopy(settings.DEFAULTS)
        s["lock"].update(lock)
        return s

    @staticmethod
    def _blocks(text):
        """{"kind": [body, ...]} for the top-level `name { ... }` blocks."""
        out = {}
        for m in re.finditer(r"^([a-z-]+) \{\n(.*?)^\}", text, re.S | re.M):
            out.setdefault(m.group(1), []).append(m.group(2))
        return out

    def test_hyprlock_defaults_match_static_design(self):
        b = self._blocks(render.render_hyprlock(self._settings()))
        self.assertEqual({k: len(v) for k, v in b.items()},
                         {"general": 1, "animations": 1, "background": 1, "image": 1, "label": 4, "input-field": 1})
        self.assertIn("blur_passes = 3", b["background"][0])
        self.assertIn("blur_size = 7", b["background"][0])
        self.assertIn("brightness = 0.75", b["background"][0])
        self.assertIn("position = 0, 260", b["image"][0])
        self.assertIn("size = 84", b["image"][0])
        self.assertIn("rounding = -1", b["image"][0])
        labels = "\n".join(b["label"])
        for needle in ("text = Welcome $USER", "font_size = 18", "position = 0, 190",
                       'date +"%A, %d %B %Y"', "font_size = 14", "position = 0, 125",
                       'date +"%H:%M"', "font_size = 96", "position = 0, 50",
                       "bbkos-lock-battery", "font_size = 13", "position = 0, -150"):
            self.assertIn(needle, labels)
        f = b["input-field"][0]
        for needle in ("size = 300, 50", "position = 0, -70", "outline_thickness = 0", "rounding = -1",
                       "inner_color = rgba(255, 255, 255, 0.14)"):
            self.assertIn(needle, f)

    def test_hyprlock_background_follows_the_saved_wallpaper(self):
        s = self._settings()
        s["wallpaper"]["path"] = "/home/x/.local/share/bbkos/wallpaper/current.png"
        b = self._blocks(render.render_hyprlock(s))
        self.assertIn("path = /home/x/.local/share/bbkos/wallpaper/current.png", b["background"][0])

    def test_hyprlock_background_without_wallpaper_is_a_colour(self):
        b = self._blocks(render.render_hyprlock(self._settings()))     # defaults: no wallpaper
        self.assertNotIn("path =", b["background"][0])
        self.assertIn("color = ", b["background"][0])

    def test_hyprlock_left_and_right_align_use_the_edge_margin(self):
        t = render.render_hyprlock(self._settings(timeAlign="left", dateAlign="right", edgeMargin=12, timeX=300))
        b = self._blocks(t)
        labels = {("96" in x and "time") or ("14" in x and "date") or "": x for x in b["label"]}
        self.assertIn("halign = left", labels["time"])
        self.assertIn("position = 12%, 50", labels["time"])          # X is not used when aligned
        self.assertIn("halign = right", labels["date"])
        self.assertIn("position = -12%, 125", labels["date"])

    def test_hyprlock_field_and_avatar_can_align(self):
        b = self._blocks(render.render_hyprlock(self._settings(fieldAlign="right", avatarAlign="left")))
        self.assertIn("position = -10%, -70", b["input-field"][0])
        self.assertIn("halign = right", b["input-field"][0])
        self.assertIn("position = 10%, 260", b["image"][0])
        self.assertIn("halign = left", b["image"][0])

    def test_hyprlock_center_is_unchanged_and_uses_x(self):
        b = self._blocks(render.render_hyprlock(self._settings(timeX=40)))
        t = [x for x in b["label"] if "font_size = 96" in x][0]
        self.assertIn("halign = center", t)
        self.assertIn("position = 40, 50", t)

    def test_hyprlock_hidden_element_has_no_block(self):
        b = self._blocks(render.render_hyprlock(self._settings(avatarShow=False, welcomeShow=False)))
