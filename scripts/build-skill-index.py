#!/usr/bin/env python3
"""build-skill-index.py [--repo PATH] [--check]

Writes .claude/skills/bbkos/modules-index.md: one line per module doc (docs/modules/*.md) and decision
(docs/decisions/*.md) with its title and first sentence, then one line per bbkos-* command in
dotfiles/bin/.local/bin with the first sentence of its header comment, so the bbkOS skill can point an agent at the
right doc or command.
--check changes nothing: it exits 1 (with a diff on stderr) when the file on disk differs from what would be written.
Standard library only; the output has no timestamps and is the same on every run (docs/specs/2026-10-20-bbkos-skill-design.md).
"""
import argparse
import difflib
import re
import sys
from pathlib import Path

INDEX = ".claude/skills/bbkos/modules-index.md"
SOURCES = ("docs/modules", "docs/decisions")
COMMAND = "python3 scripts/build-skill-index.py"
HEADER = f"""# bbkOS docs index (generated)

Generated by `scripts/build-skill-index.py` from `docs/modules/` and `docs/decisions/`. Do not edit by hand:
after adding or renaming a doc, run `{COMMAND}` (the tests fail until you do).
Find the doc for your topic here, then read it in full before changing anything it describes.

"""
NOT_PROSE = re.compile(r"^(#|\||-|\*|>|\d+\.)")
COMMANDS = "dotfiles/bin/.local/bin"
STATUS = re.compile(r"^(Applied|Status|Design|Task \d+)\b")        # metadata lines say nothing about what the doc covers


def title_of(text: str, fallback: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def summary_of(text: str, limit: int = 160) -> str:
    lines = text.splitlines()
    start = next((i + 1 for i, l in enumerate(lines) if l.startswith("# ")), 0)
    in_fence = False
    for line in lines[start:]:
        s = line.strip()
        if s.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence or not s or NOT_PROSE.match(s) or STATUS.match(s):
            continue
        sentence = s.split(". ", 1)[0].rstrip(".").strip()
        if len(sentence) > limit:
            sentence = sentence[:limit - 1].rstrip() + "…"
        return sentence
    return ""


def command_summary(text: str, name: str, limit: int = 160) -> str:
    """First sentence of a command's header comment or docstring, skipping the shebang and usage-only lines
    (`# bbkos-x [ARGS]`), without a leading `bbkos-x:`, joined across wrapped comment lines. Empty when the file
    starts with code instead."""
    buf = []
    for line in text.replace("\r\n", "\n").splitlines()[1:]:
        s = line.strip()
        if s.startswith("#"):
            s = s[1:].strip()
        elif s.startswith('"""'):
            s = s[3:].strip()
        elif s:
            break
        s = s.removesuffix('"""').strip()
        if not s:
            if buf:
                break
            continue
        if not buf:
            if s.startswith(name + ":"):
                s = s[len(name) + 1:].strip()
            elif (s == name or s.startswith(name + " ")) and ":" not in s:
                continue
        buf.append(s)
        if ". " in " ".join(buf) + " ":
            break
    sentence = (" ".join(buf) + " ").split(". ", 1)[0].rstrip(".").strip()
    return sentence if len(sentence) <= limit else sentence[:limit - 1].rstrip() + "…"


def build(repo: Path) -> str:
    out = [HEADER]
    paths = sorted(p for d in SOURCES for p in (repo / d).glob("*.md"))
    for p in paths:
        text = p.read_text(encoding="utf-8").replace("\r\n", "\n")
        rel = p.relative_to(repo).as_posix()
        title, summary = title_of(text, p.name), summary_of(text)
        out.append(f"- `{rel}`: {title}" + (f". {summary}" if summary else "") + "\n")
    out.append("\n## Commands\n\n")
    for p in sorted((repo / COMMANDS).glob("bbkos-*")):
        if p.is_file():
            summary = command_summary(p.read_text(encoding="utf-8"), p.name)
            out.append(f"- `{p.name}`" + (f": {summary}" if summary else "") + "\n")
    return "".join(out)


def main(argv: list) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    target = args.repo / INDEX
    wanted = build(args.repo)
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current == wanted:
            return 0
        diff = "".join(difflib.unified_diff(current.splitlines(True), wanted.splitlines(True), "on disk", "generated"))
        sys.stderr.write(f"{INDEX} is out of date.\n{diff}\nrun: {COMMAND}\n")
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
