#!/usr/bin/env python3
"""build-settings-index.py [--repo PATH] [--check]

Writes modules/settings/SearchIndex.js in the Quickshell config: one entry per setting row of the settings window (its label,
hint, card title and the place "page/tab" where it is), read from modules/settings/Pages.js (which tab draws which Page*.qml)
and the Page*.qml files (each `label: "..."` of a row, with its `hint: "..."` and the title of the SettingsSection around it).
The sidebar search uses it to find single settings, not only pages, and to jump to the row.
Labels built at run time (Repeaters: keybindings, apps, devices) are not in it; the Accessibility page gathers rows that have
their own page, so it is skipped (no double hits).
--check changes nothing: it exits 1 (with a diff on stderr) when the file on disk differs from what would be written.
Standard library only; the output has no timestamps and is the same on every run.
"""
import argparse
import difflib
import json
import re
import sys
from pathlib import Path

SETTINGS = "dotfiles/quickshell/.config/quickshell/modules/settings"
OUT = SETTINGS + "/SearchIndex.js"
COMMAND = "python3 scripts/build-settings-index.py"
SKIP = {"PageAccessibility"}

PAGE = re.compile(r'\{ id: "(?P<pid>[\w-]+)", label: "(?P<plabel>[^"]+)", group:')
TAB = re.compile(r'\{ id: "(?P<tid>[\w-]+)", label: "(?P<tlabel>[^"]+)", page: "(?P<file>\w+)"')
TOKEN = re.compile(r'SettingsSection \{|title: "(?P<title>[^"]*)"|label: "(?P<label>[^"]*)"')
HINT = re.compile(r'\bhint: "(?P<hint>[^"]*)"')


def places(pages_js):
    """[(place, where, file)] in Pages.js order."""
    out = []
    page = None
    for m in sorted(list(PAGE.finditer(pages_js)) + list(TAB.finditer(pages_js)), key=lambda m: m.start()):
        if m.re is PAGE:
            page = (m["pid"], m["plabel"])
            continue
        if page is None:
            raise ValueError(f"tab {m['tid']} before any page in Pages.js")
        out.append((f"{page[0]}/{m['tid']}", page[1], m["tlabel"], m["file"]))
    # A page with one tab shows no tab bar: its rows read "Page", not "Page › Tab".
    counts = {}
    for place, *_ in out:
        counts[place.split("/")[0]] = counts.get(place.split("/")[0], 0) + 1
    return [(place, plabel if counts[place.split("/")[0]] == 1 else f"{plabel} › {tlabel}", file)
            for place, plabel, tlabel, file in out]


def object_start(text, pos):
    """Index of the `{` that opens the QML/JS object around pos."""
    depth = 0
    for i in range(pos - 1, -1, -1):
        c = text[i]
        if c == "}":
            depth += 1
        elif c == "{":
            if depth == 0:
                return i
            depth -= 1
    return 0


def rows(qml):
    """[(label, hint, section)] for each row label in a Page*.qml, in file order."""
    out = []
    section = ""
    expect_title = False
    for m in TOKEN.finditer(qml):
        if m.group(0).startswith("SettingsSection"):
            expect_title, section = True, ""
            continue
        if m["title"] is not None:
            if expect_title:
                section, expect_title = m["title"], False
            continue
        start = object_start(qml, m.start())
        before = qml[start:m.start()]
        if "value:" in before or re.search(r'\bid: "', before):
            continue                                                     # a chip ({ value, label }) or a list entry ({ id: "x", label }), not a row
        end = qml.find("}", m.end())
        obj = qml[start:end if end >= 0 else len(qml)]
        if re.search(r'label: "[^"]*"\s*\+', qml[m.start():m.end() + 4]):
            continue                                                     # built at run time
        h = HINT.search(obj)
        out.append((m["label"], h["hint"] if h else "", section))
    return out


def build(repo):
    base = Path(repo) / SETTINGS
    entries = []
    for place, where, file in places((base / "Pages.js").read_text(encoding="utf-8")):
        if file in SKIP:
            continue
        path = base / (file + ".qml")
        if not path.exists():
            raise FileNotFoundError(f"{path} (named in Pages.js)")
        seen = set()
        for label, hint, section in rows(path.read_text(encoding="utf-8")):
            if not label or (label, section) in seen:
                continue
            seen.add((label, section))
            entries.append({"label": label, "hint": hint, "section": section, "place": place, "where": where})
    lines = [".pragma library",
             f"// Generated by scripts/build-settings-index.py from Pages.js and the Page*.qml files. Do not edit by hand:",
             f"// after adding, moving or renaming a setting row, run `{COMMAND}` (tests/theme fails until you do).",
             "// One entry per row: label, hint, section (card title), place (\"page/tab\") and where (\"Page › Tab\").",
             "var ROWS = ["]
    lines += ["    " + json.dumps(e, ensure_ascii=False) + "," for e in entries]
    lines[-1] = lines[-1].rstrip(",")
    lines.append("]")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", default=str(Path(__file__).resolve().parents[1]))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = build(a.repo)
    out = Path(a.repo) / OUT
    if a.check:
        old = out.read_text(encoding="utf-8") if out.exists() else ""
        if old != text:
            sys.stderr.writelines(difflib.unified_diff(old.splitlines(True), text.splitlines(True), str(out), "expected"))
            print(f"{OUT} is stale: run {COMMAND}", file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({text.count(chr(10)) - 6} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
